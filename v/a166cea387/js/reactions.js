// The reaction table (REWRITE_PLAN.md 5d-2; audit/03 §5.3): every reaction
// the world runs, a row each, saying what reacts, when, into what, how fast,
// with what heat, and what passes between the two sides. The numbers are
// the element table's columns each row names (js/elements.js, per element,
// in physical units), which is where an element's part in a reaction is
// set: wood burns because it has a burnTime and the oxygen it burns with,
// charcoal is what it chars into because its charTo says so. Each
// reaction's code is a physical law (a rate of oxygen, Richards' equation,
// Faraday's), in the pass its row names, rather than a rule compiled from
// the row: the row is its specification, and gives the tooltips their
// lines (describe in js/elements.js). js/elements.js checks the columns
// named are the table's. `test/reactions.mjs` prints the table.
//
// Each row: `applies(e)`, whether element e takes part; `text(e, name)`,
// its tooltip line for e (name(id) an element's name), or null.

